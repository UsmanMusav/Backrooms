// Optional deterministic, dependency-free training. Normal builds use checked-in weights.
// Run: node --experimental-strip-types scripts/train-mimic.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { infer, textFeatures, best } from '../shared/neural-core.ts';
import { seededRandom } from '../src/level.ts';
import { actions, intents, dialogue, teacher } from './mimic-demonstrations.mjs';
const random = seededRandom(93147);
function network(inputs, hidden, outputs) {
  const weights = (size, fan) => Array.from({ length: size }, () => (random() * 2 - 1) * Math.sqrt(3 / fan));
  return { inputs, hidden, outputs, w1: weights(inputs * hidden, inputs), b1: Array(hidden).fill(0), w2: weights(hidden * outputs, hidden), b2: Array(outputs).fill(0) };
}
function train(model, samples, epochs, initialRate) {
  const hidden = Array(model.hidden), logits = Array(model.outputs), gradient = Array(model.hidden);
  for (let epoch = 0; epoch < epochs; epoch++) {
    const rate = initialRate * (1 - epoch / epochs * .72);
    for (let i = samples.length - 1; i > 0; i--) { const j = Math.floor(random() * (i + 1)); [samples[i], samples[j]] = [samples[j], samples[i]]; }
    for (const [input, expected] of samples) {
      for (let h = 0; h < model.hidden; h++) {
        let value = model.b1[h]; for (let i = 0; i < model.inputs; i++) value += input[i] * model.w1[h * model.inputs + i];
        hidden[h] = Math.tanh(value); gradient[h] = 0;
      }
      for (let o = 0; o < model.outputs; o++) { let value = model.b2[o]; for (let h = 0; h < model.hidden; h++) value += hidden[h] * model.w2[o * model.hidden + h]; logits[o] = value; }
      const max = Math.max(...logits); let total = 0; for (let o = 0; o < model.outputs; o++) total += logits[o] = Math.exp(logits[o] - max);
      for (let o = 0; o < model.outputs; o++) {
        const error = logits[o] / total - (o === expected ? 1 : 0); model.b2[o] -= rate * error;
        for (let h = 0; h < model.hidden; h++) { const at = o * model.hidden + h; gradient[h] += error * model.w2[at]; model.w2[at] -= rate * error * hidden[h]; }
      }
      for (let h = 0; h < model.hidden; h++) {
        const error = gradient[h] * (1 - hidden[h] ** 2); model.b1[h] -= rate * error;
        for (let i = 0; i < model.inputs; i++) model.w1[h * model.inputs + i] -= rate * error * input[i];
      }
    }
  }
  for (const key of ['w1', 'w2', 'b1', 'b2']) model[key] = model[key].map(value => +value.toFixed(6));
  return model;
}
const observation = () => [random() ** 2, random() > .22 ? 1 : 0, random() > .35 ? 1 : 0, random() > .75 ? 1 : 0, Math.floor(random() * 4) / 3, (1 + Math.floor(random() * 4)) / 4, random(), random(), random() > .5 ? 1 : 0, random() > .75 ? 1 : 0, random() > .8 ? 1 : 0, random()];
const buckets = actions.map(() => []);
for (let i = 0; i < 100000 && buckets.some(b => b.length < 650); i++) { const x = observation(), label = teacher(x); if (buckets[label].length < 650) buckets[label].push([x, label]); }
const policySamples = buckets.flat(), policyValidation = Array.from({ length: 3000 }, () => { const x = observation(); return [x, teacher(x)]; });
const policy = train(network(12, 28, actions.length), policySamples, 110, .025);
const dialogueSamples = [], dialogueValidation = [];
for (const [intent, phrases] of dialogue) for (let i = 0; i < phrases.length; i++) {
  const label = intents.indexOf(intent);
  for (const prefix of ['', 'ребят ', 'эй ']) for (const suffix of ['', '?', ' пожалуйста']) dialogueSamples.push([textFeatures(prefix + phrases[i] + suffix), label]);
  for (const text of ['народ, ' + phrases[i] + '...', 'а ' + phrases[i] + '??']) dialogueValidation.push([textFeatures(text), label]);
}
const language = train(network(256, 48, intents.length), dialogueSamples, 100, .04);
const accuracy = (model, data) => +(data.filter(([x, label]) => best(infer(model, x)) === label).length / data.length).toFixed(4);
const metadata = { version: 1, seed: 93147, method: 'synthetic-supervised-imitation', policySamples: policySamples.length, policyValidationSamples: policyValidation.length, policyValidationAccuracy: accuracy(policy, policyValidation), dialogueSamples: dialogueSamples.length, dialogueValidationSamples: dialogueValidation.length, dialogueValidationAccuracy: accuracy(language, dialogueValidation), dialogueValidationMethod: 'held-out perturbations of known synthetic phrases, NOT unseen semantic topics', warning: 'Small behaviour and intent networks, NOT a generative language model or human-trained intelligence.' };
console.log(JSON.stringify(metadata, null, 2));
if (metadata.policyValidationAccuracy < .88 || metadata.dialogueValidationAccuracy < .85) throw new Error('Synthetic validation failed; existing weights preserved');
mkdirSync('shared/ai', { recursive: true });
writeFileSync('shared/ai/weights.ts', '// Generated by scripts/train-mimic.mjs from original synthetic demonstrations. No player data.\n' + `export const TRAINING = ${JSON.stringify(metadata)};\nexport const POLICY = ${JSON.stringify(policy)};\nexport const DIALOGUE = ${JSON.stringify(language)};\n`);
